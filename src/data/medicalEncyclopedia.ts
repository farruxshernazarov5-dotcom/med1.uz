// Get all unique letters that have terms
export const getAvailableLetters = (): string[] => {
  const letters = new Set(encyclopediaTerms.map((t) => t.letter));
  return "ABCDEFGHIJKLMNOPQRSTUVWXYZ".split("").filter((l) => letters.has(l));
};

// Get terms by letter
export const getTermsByLetter = (letter: string): MedicalTerm[] => {
  return encyclopediaTerms.filter((t) => t.letter === letter).sort((a, b) => a.term.localeCompare(b.term));
};

// Get terms by category
export const getTermsByCategory = (category: string): MedicalTerm[] => {
  return encyclopediaTerms.filter((t) => t.category === category);
};

// Search terms
export const searchTerms = (query: string): MedicalTerm[] => {
  const q = query.toLowerCase();
  return encyclopediaTerms.filter(
    (t) =>
      t.term.toLowerCase().includes(q) ||
      t.shortDesc.toLowerCase().includes(q) ||
      t.fullDesc.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q)
  );
};

// Get term count per letter
export const getTermCountByLetter = (letter: string): number => {
  return encyclopediaTerms.filter((t) => t.letter === letter).length;
};

// Get total term count
export const getTotalTermCount = (): number => encyclopediaTerms.length;
